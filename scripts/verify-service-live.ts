import assert from 'node:assert/strict';

// This opt-in test writes synthetic data only to an explicitly selected loopback service.
const base = process.env.SERVICE_TEST_URL;
const token = process.env.SERVICE_TEST_TOKEN;
assert(base && token, 'Set SERVICE_TEST_URL and SERVICE_TEST_TOKEN for an isolated local service.');
assert(['127.0.0.1', 'localhost', '[::1]'].includes(new URL(base).hostname), 'Live tests only target loopback.');
const data = new Map<string, string>();
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: (k: string) => data.get(k) ?? null, setItem: (k: string,v: string) => data.set(k,v), removeItem: (k: string) => data.delete(k) }, configurable:true });
(globalThis as any).window = new EventTarget();
const { useDataSourceStore } = await import('../src/store/dataSourceStore');
const { useKnowledgeStore } = await import('../src/store/knowledgeStore');
const { useChatStore } = await import('../src/store/chatStore');
const { useDutyScheduleStore } = await import('../src/store/dutyScheduleStore');
const { sourceRequest } = await import('../src/utils/dataSourceRequest');
const { fetchBankIndex } = await import('../src/utils/bankIndex');
const { fetchDutyIndex } = await import('../src/utils/dutyScheduleIndex');
const { fetchRemoteJson } = await import('../src/utils/remoteRepo');
const { hydrateSourceBank } = await import('../src/utils/dataSourceAssets');
const { syncDataNow } = await import('../src/utils/dataSync');
const { fetchPublicResources } = await import('../src/utils/publicResources');
const { useQuestionBankStore: bankStore } = await import('../src/store/questionBankStore');
const { mergeSyncedSummaryVersions } = await import('../src/utils/knowledgeSummary');
const space=`live-test-${crypto.randomUUID()}`;
useDataSourceStore.getState().configure(base,token,space);
for (const entry of useDataSourceStore.getState().sources) if (entry.kind !== 'service') useDataSourceStore.getState().setSourceEnabled(entry.id, false);
assert.equal((await sourceRequest<any>('api/v1/health')).data.service,'question-bank-service');
const banks=await fetchBankIndex(); assert(banks && banks.userBanks.length>0);
const bank=banks.userBanks[0];
const content=await hydrateSourceBank(await fetchRemoteJson(bank.downloadUrl),bank.downloadUrl,bank.imagePath);
assert(Array.isArray(content.questions) && content.questions.length>0);
const duties=await fetchDutyIndex(); assert(duties && duties.userDuties.length>0);
const dutyData=await fetchRemoteJson<any>(duties.userDuties[0].downloadUrl); assert(Array.isArray(dutyData.shifts));
const now=new Date().toISOString();
useKnowledgeStore.setState({items:[{id:'live-local-note',title:'Local contract test',category:'test',content:'Synthetic test data',createdAt:now,updatedAt:now}],categories:['test']});
useChatStore.getState().createConversation('Local contract test');useChatStore.getState().addMessage({role:'user',content:'Synthetic test message',source:'ai'});
useDutyScheduleStore.setState({isLoaded:true,duties:[{id:'live-duty',name:'Local contract test',shifts:[],createdAt:now,updatedAt:now}]});
await mergeSyncedSummaryVersions('combined',[{id:'live-summary',version:'v1',content:'Synthetic summary',createdAt:Date.now()}]);
for(const kind of ['knowledge','summaries','chat','duty'] as const)useDataSourceStore.getState().setSync(kind,true);
await syncDataNow();
assert(useKnowledgeStore.getState().items.length>1,'Published documents should merge with local content.');
const revisions: number[]=[];
for(const kind of ['knowledge','summaries','chat']){ const result=await sourceRequest<any>(`api/v1/sync/${space}/${kind}`); assert(result.data.revision>=1);revisions.push(result.data.revision); }
assert.equal((await sourceRequest<any>(`api/v1/sync/${space}/duty`)).data.revision,0,'Public duty data must not upload into a personal space.');
await syncDataNow();
for(const [i,kind] of ['knowledge','summaries','chat'].entries()){ const result=await sourceRequest<any>(`api/v1/sync/${space}/${kind}`); assert.equal(result.data.revision,revisions[i],'Unchanged data should not cause another upload.'); }
console.log('PASS: real HTTP auth, public duty download without upload, three personal channels and idempotent re-sync.');
bankStore.setState({ isLoaded: true, banks: [] });
const localId = bankStore.getState().addBank({ name: 'Synthetic local bank', questions: [{ id:'local-q',type:'subjective',question:'合成测试题',correctAnswer:'测试答案',score:1,category:'test',difficulty:'easy' }] });
useDataSourceStore.getState().setSync('banks',true);
await fetchPublicResources('banks', {url:base,token}, () => true);
assert.equal(useDataSourceStore.getState().lastError, '');
assert(bankStore.getState().banks.length >= 2, 'Published bank should import automatically.');
await assert.rejects(sourceRequest<any>(`api/v1/bank-sync/${space}/banks/${localId}`), /不存在|HTTP 404/);
const ids = bankStore.getState().banks.map(b => b.id).sort();
useDataSourceStore.getState().setSpace(`${space}-other`);
await fetchPublicResources('banks', {url:base,token}, () => true);
assert.deepEqual(bankStore.getState().banks.map(b => b.id).sort(),ids,'Changing personal space must not duplicate public banks.');
assert.equal(bankStore.getState().banks.find(b => b.id === localId)?.name,'Synthetic local bank');
console.log('PASS: public bank download, no local-bank upload, local data preserved and public resources independent of personal space.');
